/** "RS" -> "RS - Rio Grande do Sul", for labeling a state code someone unfamiliar with Brazilian geography wouldn't recognize on its own. */
export function formatStateLabel(code: string): string {
  const name = STATE_NAMES[code];
  return name ? `${code} - ${name}` : code;
}
